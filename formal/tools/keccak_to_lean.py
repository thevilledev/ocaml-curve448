C_BEGIN = "-- BEGIN VERBATIM lib/c/native/shake256.h"
C_END = "-- END VERBATIM lib/c/native/shake256.h"


def c_modelled_text(c_src):
    """The part of shake256.h that Keccak.lean models: from the round constant
    table to the end of keccak_f1600 (and the #undef after it)."""
    start = c_src.index("static const uint64_t KECCAK_ROUND_CONSTANTS[24]")
    end = c_src.index("#undef KECCAK_ROTL")
    end = c_src.index("\n", end)
    return c_src[start:end].strip("\n")


def c_tables(text):
    def body(name):
        m = re.search(re.escape(name) + r"\s*\[\s*24\s*\]\s*=\s*\{(.*?)\}\s*;", text, re.S)
        if not m:
            raise Error("table %s not found" % name)
        return m.group(1)
    rc = [int(v, 16) for v in re.findall(r"UINT64_C\(\s*0x([0-9a-fA-F]+)\s*\)",
                                          body("KECCAK_ROUND_CONSTANTS"))]
    rho = [int(v) for v in re.findall(r"\d+", body("KECCAK_RHO"))]
    pi = [int(v) for v in re.findall(r"\d+", body("KECCAK_PI"))]
    return rc, rho, pi


def lean_tables(text):
    def body(name):
        m = re.search(r"def\s+" + re.escape(name) + r"\s*:[^=]*:=\s*\[(.*?)\]", text, re.S)
        if not m:
            raise Error("Lean definition of %s not found in Keccak.lean" % name)
        return m.group(1)
    rc = [int(v, 16) for v in re.findall(r"0x([0-9a-fA-F]+)#64", body("KECCAK_ROUND_CONSTANTS"))]
    rho = [int(v) for v in re.findall(r"\d+", body("KECCAK_RHO"))]
    pi = [int(v) for v in re.findall(r"\d+", body("KECCAK_PI"))]
    return rc, rho, pi


def check_c_model():
    with open(C_SRC, encoding="utf-8") as handle:
        c_src = handle.read()
    with open(LEAN_C_MODEL, encoding="utf-8") as handle:
        lean = handle.read()
    try:
        quoted = lean[lean.index(C_BEGIN) + len(C_BEGIN):lean.index(C_END)].strip("\n")
    except ValueError:
        raise Error("verbatim C quote markers not found in %s" % LEAN_C_MODEL)
    if quoted != c_modelled_text(c_src):
        raise Error("keccak_f1600 in lib/c/native/shake256.h differs from the copy modelled in "
                    "formal/lean/Curve448Formal/Keccak.lean; update the Lean C model")
    if c_tables(c_src) != lean_tables(lean):
        raise Error("the C tables and their Lean definitions in Keccak.lean differ")
    rc, rho, pi = c_tables(c_src)
    if not (len(rc) == len(rho) == len(pi) == 24):
        raise Error("a C table does not have 24 entries")


def main(argv):
    args = argv[1:]
    if args not in ([], ["--check"], ["--stdout"]):
        sys.stderr.write(__doc__)
        return 2
    with open(OCAML_SRC, encoding="utf-8") as handle:
        src = handle.read()
    try:
        text = generate(src)
        if args == ["--check"]:
            check_c_model()
    except Error as e:
        sys.stderr.write("keccak_to_lean: %s\n" % e)
        return 1
    if args == ["--stdout"]:
        sys.stdout.write(text)
        return 0
    if args == ["--check"]:
        try:
            with open(LEAN_OUT, encoding="utf-8") as handle:
                current = handle.read()
        except FileNotFoundError:
            current = None
        if current != text:
            sys.stderr.write("keccak_to_lean: %s is out of date; run "
                             "python3 formal/tools/keccak_to_lean.py\n"
                             % os.path.relpath(LEAN_OUT, ROOT))
            return 1
        return 0
    with open(LEAN_OUT, "w", encoding="utf-8") as handle:
        handle.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
